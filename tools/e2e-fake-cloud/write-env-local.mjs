// Installs the rig's throwaway values into web/.env.local (backing up whatever was
// there) and restores them afterwards.
//
// Why a file instead of plain process env: Next.js runs every loaded .env file
// through dotenv-expand, and expand() writes its result back into process.env for
// each key the file declares. ADMIN_KEY_HASH contains `$` separators, so an
// unescaped value is silently rewritten as variable interpolation - which is also
// why the tracked .env.local escapes them as `\$`.
//
//   node write-env-local.mjs --port 3100 --commit <sha>
//   node write-env-local.mjs --restore
import { copyFileSync, existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const webDir = join(import.meta.dirname, "../../web");
const envLocal = join(webDir, ".env.local");
const backup = join(webDir, ".env.local.e2e-backup");
const stateDir = process.env.FAKE_CLOUD_STATE ?? join(tmpdir(), "ytb-vps-e2e-cloud");

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? fallback : process.argv[index + 1];
}

if (process.argv.includes("--restore")) {
  if (existsSync(backup)) {
    rmSync(envLocal, { force: true });
    renameSync(backup, envLocal);
    console.log("restored web/.env.local");
  } else {
    console.log("no backup present; leaving web/.env.local untouched");
  }
  process.exit(0);
}

const port = argumentValue("port", "3100");
const commit = argumentValue("commit", "0".repeat(40));
const values = JSON.parse(readFileSync(join(stateDir, "env.json"), "utf8"));

if (existsSync(envLocal) && !existsSync(backup)) copyFileSync(envLocal, backup);

const lines = [
  "# Generated by tools/e2e-fake-cloud for a local end-to-end run.",
  "# The original file is saved as .env.local.e2e-backup; restore with `--restore`.",
  "NODE_ENV=development",
  `DATABASE_URL=${values.DATABASE_URL}`,
  // `$` must be escaped: Next expands .env values through dotenv-expand.
  `ADMIN_KEY_HASH=${values.ADMIN_KEY_HASH.replaceAll("$", "\\$")}`,
  `SESSION_SECRET=${values.SESSION_SECRET}`,
  `APP_ORIGIN=http://localhost:${port}`,
  `GOOGLE_OAUTH_CLIENT_ID=${values.GOOGLE_OAUTH_CLIENT_ID}`,
  `GOOGLE_OAUTH_CLIENT_SECRET=${values.GOOGLE_OAUTH_CLIENT_SECRET}`,
  `DRIVE_TOKEN_KEY_V1=${values.DRIVE_TOKEN_KEY_V1}`,
  `NEON_STORAGE_LIMIT_BYTES=${values.NEON_STORAGE_LIMIT_BYTES}`,
  `DRIVE_UPLOAD_MAX_BYTES=${values.DRIVE_UPLOAD_MAX_BYTES}`,
  `FREE_TIER_SOFT_PERCENT=${values.FREE_TIER_SOFT_PERCENT}`,
  `QUOTA_STALE_AFTER_SECONDS=${values.QUOTA_STALE_AFTER_SECONDS}`,
  `WORKER_AUTH_KEY_V1=${values.WORKER_AUTH_KEY_V1}`,
  `WORKER_RELEASE_REPOSITORY=${values.WORKER_RELEASE_REPOSITORY}`,
  `WORKER_RELEASE_COMMIT=${commit}`,
  `WORKER_PIPELINE_BRIDGE_VERSION=${values.WORKER_PIPELINE_BRIDGE_VERSION}`,
];

writeFileSync(envLocal, `${lines.join("\n")}\n`, { mode: 0o600 });
console.log(`wrote web/.env.local for port ${port} at commit ${commit}`);
